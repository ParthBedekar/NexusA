    /**
     * Rule: ENTITY_TYPE
     * Validates that entity types declared in the payload are from the supported set.
     * Catches typos like "Civilizaton" instead of "Civilization".
     */
    @Component
    public static class EntityTypeRule implements ValidationRule {
    
        private static final Set<String> SUPPORTED_ENTITY_TYPES = Set.of(
                "Civilization", "Person", "Event", "Location",
                "Artifact", "Dynasty", "Religion", "Language", "Trade Route"
        );
    
        @Override
        public String getRuleCode() { return "ENTITY_TYPE"; }
    
        @Override
        public String getDescription() { return "Validates that all entity types in the payload belong to the supported set"; }
    
        @Override
        public List<ValidationError> validate(ValidationContext context) {
            List<ValidationError> errors = new ArrayList<>();
            Map<String, Object> payload = context.getParsedPayload();
            if (payload == null) return errors;
    
            // Check top-level entityType field
            Object topLevel = payload.get("entityType");
            if (topLevel instanceof String type && !type.isBlank()) {
                if (!SUPPORTED_ENTITY_TYPES.contains(type)) {
                    errors.add(buildError("rawStructuredPayload.entityType", type));
                }
            }
    
            // Check entity types inside nodes
            Object nodesRaw = payload.get("nodes");
            if (nodesRaw instanceof List<?> nodes) {
                for (int i = 0; i < nodes.size(); i++) {
                    Object nodeObj = nodes.get(i);
                    if (nodeObj instanceof Map<?, ?> node) {
                        Object et = node.get("entityType");
                        if (et instanceof String entityType && !entityType.isBlank()) {
                            if (!SUPPORTED_ENTITY_TYPES.contains(entityType)) {
                                errors.add(buildError("rawStructuredPayload.nodes[" + i + "].entityType", entityType));
                            }
                        }
                    }
                }
            }
    
            return errors;
        }
    
        private ValidationError buildError(String fieldPath, String rejectedType) {
            return ValidationError.builder()
                    .ruleCode(getRuleCode())
                    .fieldPath(fieldPath)
                    .message("Unsupported entity type: '" + rejectedType + "'. Allowed types: " + SUPPORTED_ENTITY_TYPES)
                    .severity(ValidationSeverity.ERROR)
                    .rejectedValue(rejectedType)
                    .build();
        }
    }

