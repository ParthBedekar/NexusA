/**
 * Orchestrates the full validation lifecycle:
 * - Parses JSONB payloads into Maps
 * - Builds ValidationContext objects
 * - Runs the ValidationPipeline (single or batch)
 * - Persists ValidationLog audit records
 */
@Service
@org.springframework.transaction.annotation.Transactional
public class StructuralValidationService {

    private final ValidationPipeline pipeline;
    private final ResearchSubmissionRepository submissionRepository;
    private final ValidationLogRepository logRepository;
    private final UserRepository userRepository;
    private final ObjectMapper objectMapper;

    public StructuralValidationService(ValidationPipeline pipeline,
                                       ResearchSubmissionRepository submissionRepository,
                                       ValidationLogRepository logRepository,
                                       UserRepository userRepository,
                                       ObjectMapper objectMapper) {
        this.pipeline = pipeline;
        this.submissionRepository = submissionRepository;
        this.logRepository = logRepository;
        this.userRepository = userRepository;
        this.objectMapper = objectMapper;
    }

    private User getAuthenticatedUser() {
        String mail = SecurityContextHolder.getContext().getAuthentication().getPrincipal().toString();
        return userRepository.findUserByEmail(mail)
                .orElseThrow(() -> new RuntimeException("Authenticated user not found"));
    }

    /**
     * Validates a single submission and persists the audit log.
     */
    @Transactional
    public ValidationResult validateSubmission(UUID submissionId) {
        User user = getAuthenticatedUser();
        ResearchSubmission submission = submissionRepository.findById(submissionId)
                .orElseThrow(() -> new RuntimeException("Submission not found: " + submissionId));

        ValidationContext context = buildContext(submission);
        ValidationResult result = pipeline.run(context);

        persistLog(result, submission.getSubmissionId(), user.getUserId());
        return result;
    }

    /**
     * Validates a batch of submissions and returns a full report.
     */
    @Transactional
    public ValidationReport validateBatch(List<UUID> submissionIds) {
        User user = getAuthenticatedUser();
        List<ValidationContext> contexts = new ArrayList<>();

        for (UUID id : submissionIds) {
            submissionRepository.findById(id).ifPresent(sub -> contexts.add(buildContext(sub)));
        }

        ValidationReport report = pipeline.runBatch(contexts);

        // Persist individual logs for each result in the batch
        for (ValidationResult result : report.getResults()) {
            persistLog(result, result.getSubmissionId(), user.getUserId());
        }

        return report;
    }

    public List<ValidationLog> getLogsForSubmission(UUID submissionId) {
        return logRepository.findBySubmissionIdOrderByValidatedAtDesc(submissionId);
    }

    public Page<ValidationLog> getBlockedLogs(Pageable pageable) {
        return logRepository.findByBlockedTrue(pageable);
    }

    // ─── Internals ────────────────────────────────────────────────────────────

    private ValidationContext buildContext(ResearchSubmission submission) {
        Map<String, Object> parsedPayload = parsePayload(submission.getRawStructuredPayload());
        return ValidationContext.builder()
                .submission(submission)
                .parsedPayload(parsedPayload)
                .build();
    }

    private Map<String, Object> parsePayload(String rawJson) {
        if (rawJson == null || rawJson.isBlank()) return null;
        try {
            return objectMapper.readValue(rawJson, new TypeReference<Map<String, Object>>() {});
        } catch (JsonProcessingException e) {
            return null; // Rules handle null payload gracefully
        }
    }

    private void persistLog(ValidationResult result, UUID submissionId, UUID triggeredById) {
        ValidationLog log = new ValidationLog();
        log.setSubmissionId(submissionId);
        log.setTriggeredBy(triggeredById);
        log.setPassed(result.isPassed());
        log.setBlocked(result.isBlocked());
        log.setTotalErrors(result.getErrorCount());
        log.setCriticalCount(result.getErrorsBySeverity(ValidationSeverity.CRITICAL).size());
        log.setErrorCount(result.getErrorsBySeverity(ValidationSeverity.ERROR).size());
        log.setWarningCount(result.getErrorsBySeverity(ValidationSeverity.WARNING).size());
        log.setInfoCount(result.getErrorsBySeverity(ValidationSeverity.INFO).size());

        try {
            log.setErrorsPayload(objectMapper.writeValueAsString(result.getErrors()));
        } catch (JsonProcessingException e) {
            log.setErrorsPayload("[]");
        }

        logRepository.save(log);
    }
}
